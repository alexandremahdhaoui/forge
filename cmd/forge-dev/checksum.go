package main

import (
	"bufio"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"strings"
)

const (
	ChecksumPrefix       = "sha256:"
	ChecksumHeaderPrefix = "// SourceChecksum: "
)

func ComputeSourceChecksum(configPath string, specPaths ...string) (string, error) {
	configData, err := os.ReadFile(configPath)
	if err != nil {
		return "", fmt.Errorf("reading config file %s: %w", configPath, err)
	}

	h := sha256.New()
	h.Write(configData)

	for _, specPath := range specPaths {
		specData, err := os.ReadFile(specPath)
		if err != nil {
			return "", fmt.Errorf("reading spec file %s: %w", specPath, err)
		}

		h.Write(specData)
	}

	checksum := hex.EncodeToString(h.Sum(nil))
	return ChecksumPrefix + checksum, nil
}

func ReadChecksumFromFile(path string) (string, error) {
	file, err := os.Open(path)
	if err != nil {
		if os.IsNotExist(err) {
			return "", nil
		}
		return "", fmt.Errorf("opening file %s: %w", path, err)
	}
	defer func() { _ = file.Close() }()

	scanner := bufio.NewScanner(file)
	lineCount := 0
	maxLines := 10

	for scanner.Scan() && lineCount < maxLines {
		line := scanner.Text()
		lineCount++

		if strings.HasPrefix(line, "# SourceChecksum: ") {
			line = "// " + strings.TrimPrefix(line, "# ")
		}

		if strings.HasPrefix(line, ChecksumHeaderPrefix) {
			checksum := strings.TrimPrefix(line, ChecksumHeaderPrefix)
			return strings.TrimSpace(checksum), nil
		}

		if !strings.HasPrefix(line, "//") && !strings.HasPrefix(line, "#") && line != "" {
			break
		}
	}

	if err := scanner.Err(); err != nil {
		return "", fmt.Errorf("reading file %s: %w", path, err)
	}

	return "", nil
}

const GeneratedHeaderMarker = "Code generated by"

func HasGeneratedHeader(content string) bool {
	return lineOneCarriesTheGeneratedHeader(content) || topLevelJSONCommentCarriesTheGeneratedHeader(content)
}

func lineOneCarriesTheGeneratedHeader(content string) bool {
	line, _, _ := strings.Cut(content, "\n")
	line = strings.TrimSpace(line)
	line = strings.TrimPrefix(line, "//")
	line = strings.TrimPrefix(line, "#")

	return strings.HasPrefix(strings.TrimSpace(line), GeneratedHeaderMarker)
}

func topLevelJSONCommentCarriesTheGeneratedHeader(content string) bool {
	var document struct {
		Comment string `json:"$comment"`
	}
	if json.Unmarshal([]byte(content), &document) != nil {
		return false
	}

	return strings.HasPrefix(strings.TrimSpace(document.Comment), GeneratedHeaderMarker)
}

func ChecksumHeader(checksum string) string {
	return ChecksumHeaderPrefix + checksum
}

func ChecksumMatches(computed, existing string) bool {
	if computed == "" || existing == "" {
		return false
	}
	return computed == existing
}
